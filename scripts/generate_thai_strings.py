def translate_xml_file(en_path, th_path):
    if not os.path.isfile(en_path):
        return
    tree = ET.parse(en_path)
    root = tree.getroot()
    for child in root:
        if child.tag == "string":
            name = child.get("name")
            if name in THAI_TRANSLATIONS:
                child.text = THAI_TRANSLATIONS[name]
        elif child.tag == "plurals":
            pass
        elif child.tag == "string-array":
            pass
    os.makedirs(os.path.dirname(th_path), exist_ok=True)
    tree.write(th_path, encoding="utf-8", xml_declaration=True)

def main():
    res_dir = "/workspace/clever-curie/app/src/main/res"
    values_dir = os.path.join(res_dir, "values")
    values_th_dir = os.path.join(res_dir, "values-th")
    os.makedirs(values_th_dir, exist_ok=True)

    for fname in os.listdir(values_dir):
        if fname.startswith("strings") and fname.endswith(".xml"):
            en_file = os.path.join(values_dir, fname)
            th_file = os.path.join(values_th_dir, fname)
            if not os.path.exists(th_file):
                translate_xml_file(en_file, th_file)
                print(f"Generated {th_file}")

if __name__ == "__main__":
    main()
